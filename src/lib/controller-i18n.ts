const dictionaries: Record<ControllerLocale, Record<TranslationKey, string>> = {
  en,
  "zh-CN": zhCN,
};

function interpolate(template: string, values: TranslationValues | undefined): string {
  if (!values) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (placeholder, name: string) => {
    const value = values[name];
    return value === undefined ? placeholder : String(value);
  });
}

export function translate(
  locale: ControllerLocale,
  key: TranslationKey,
  values?: TranslationValues,
): string {
  return interpolate(dictionaries[locale][key], values);
}

export function detectSystemLocale(languages: readonly string[] | undefined): ControllerLocale {
  for (const candidate of languages ?? []) {
    const normalized = candidate.trim().replace(/_/g, "-").toLowerCase();
    if (
      normalized === "zh" ||
      normalized === "zh-cn" ||
      normalized === "zh-sg" ||
      normalized === "zh-hans" ||
      normalized.startsWith("zh-hans-")
    ) {
      return "zh-CN";
    }
    if (normalized === "en" || normalized.startsWith("en-")) return "en";
  }
  return "en";
}

export function browserLanguages(): string[] {
  if (typeof navigator === "undefined") return [];
  const languages = Array.from(navigator.languages ?? []).filter((value) => typeof value === "string");
  if (typeof navigator.language === "string") languages.push(navigator.language);
  return languages;
}

export function isLocalePreference(value: unknown): value is LocalePreference {
  return value === "system" || value === "zh-CN" || value === "en";
}

function defaultStorage(): KeyValueStorage | null {
  try {
    // In privacy-restricted WebViews, merely resolving `localStorage` can
    // throw SecurityError. Keep both the probe and the value access inside
    // this boundary: this function is evaluated as a default argument while
    // the controller initializes, so letting it throw would blank the UI.
    if (typeof localStorage === "undefined") return null;
    return localStorage;
  } catch {
    return null;
  }
}

export function loadLocalePreference(storage: KeyValueStorage | null = defaultStorage()): LocalePreference {
  if (!storage) return "system";
  try {
    const value = storage.getItem(CONTROLLER_LOCALE_STORAGE_KEY);
    return isLocalePreference(value) ? value : "system";
  } catch {
    return "system";
  }
}

export function saveLocalePreference(
  preference: LocalePreference,
  storage: KeyValueStorage | null = defaultStorage(),
): void {
  if (!storage || !isLocalePreference(preference)) return;
  try {
    storage.setItem(CONTROLLER_LOCALE_STORAGE_KEY, preference);
  } catch {
    // Privacy modes and restrictive WebViews can reject writes. The controller
    // stays usable and simply falls back to system language next launch.
  }
}

/**
 * The native store is authoritative after it has persisted a preference. On
 * the first native-capable launch only, preserve a manual v0.2.12 browser
 * choice instead of silently replacing it with the native default.
 */
export function nativePreferenceMigration(
  nativePersisted: boolean,
  legacyPreference: LocalePreference,
): LocalePreference | null {
  return !nativePersisted && legacyPreference !== "system" ? legacyPreference : null;
}

export function resolveControllerLocale(
  preference: LocalePreference,
  languages: readonly string[] | undefined,
): ControllerLocale {
  return preference === "system" ? detectSystemLocale(languages) : preference;
}

export function formatControllerDate(locale: ControllerLocale, value: number | Date): string {
  return new Intl.DateTimeFormat(locale, { dateStyle: "medium", timeStyle: "short" }).format(value);
}
